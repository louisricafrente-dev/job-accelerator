const fs = require('node:fs');
const harness = fs.readFileSync('tests/frontend_regressions.cjs', 'utf8').split('async function main()')[0];
eval(harness + `
(async () => {
  context.currentUserRole = 'admin';
  context.currentSessionToken = token('admin', 'admin');
  const releases = [];
  const writes = [];
  context.window.fetch = (url, options) => { writes.push(JSON.parse(options.body)); return new Promise(resolve => releases.push(resolve)); };
  context.saveLocalStatusOverride(42, {notes: 'first'});
  const saving = context.flushJobOverride(42);
  context.saveLocalStatusOverride(42, {notes: 'second'});
  releases.shift()({ok: true, json: async () => ({success: true})});
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(context.getLocalStatusOverrides()['42'].notes, 'second');
  assert.equal(writes[1].notes, 'second');
  releases.shift()({ok: true, json: async () => ({success: true})});
  await saving;
  assert.equal(context.getLocalStatusOverrides()['42'], undefined);
  assert.equal(elements.get('note-save-42').textContent, 'Saved');
  context.window.fetch = async () => ({ok: false, status: 500});
  context.saveLocalStatusOverride(42, {notes: 'keep after failure'});
  await context.flushJobOverride(42);
  assert.equal(context.getLocalStatusOverrides()['42'].save_state, 'failed');
  assert.equal(elements.get('note-save-42').textContent, 'Failed - retry');
  context.window.fetch = async () => ({ok: true, json: async () => ({success: true})});
  await context.flushJobOverride(42);
  assert.equal(elements.get('note-save-42').textContent, 'Saved');

  context.viewFilters = {};
  context.CANDIDATE_DEFAULT_STACK = '';
  context.fetch = async () => ({ok: true});
  context.document.querySelectorAll = () => [];
  context.syncFilterControlsUI = () => {};
  context.loadJobs = () => {};
  vm.runInContext(code.slice(code.indexOf('const viewFilterKeys ='), code.indexOf('// Load persistent user settings')), context);
  vm.runInContext(code.slice(code.indexOf('function setStatus('), code.indexOf('function setLevel(')), context);
  context.currentStatus = 'new'; context.currentDateFilter = '7days'; context.currentRole = 'Mobile';
  context.setStatus('saved');
  assert.equal(context.currentDateFilter, 'all');
  assert.equal(context.currentRole, 'All');
  context.currentDateFilter = '3days'; context.currentRole = 'Frontend';
  context.setStatus('applied');
  assert.equal(context.currentDateFilter, 'all');
  assert.equal(context.currentRole, 'All');
  context.currentDateFilter = 'today';
  context.setStatus('saved');
  assert.equal(context.currentDateFilter, '3days');
  assert.equal(context.currentRole, 'Frontend');
  context.setStatus('new');
  assert.equal(context.currentDateFilter, '7days');
  assert.equal(context.currentRole, 'Mobile');
  const stored = storage.get('job_accel_view_filters');
  context.viewFilters = JSON.parse(stored);
  context.currentStatus = 'applied'; context.restoreViewFilters();
  assert.equal(context.currentDateFilter, 'today');
  await vm.runInContext('settingWriteQueue', context);
  const settingRequests = [];
  const acknowledgments = [];
  context.fetch = (url, options) => {
    settingRequests.push(JSON.parse(options.body));
    return new Promise(resolve => acknowledgments.push(resolve));
  };
  context.currentStatus = 'saved';
  context.currentDateFilter = '3days'; context.rememberViewFilters();
  await new Promise(resolve => setImmediate(resolve));
  context.currentDateFilter = 'all'; context.rememberViewFilters();
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(settingRequests.length, 1, 'second preference write waits for the first');
  acknowledgments.shift()({ok: true});
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(settingRequests.length, 2);
  assert.equal(JSON.parse(settingRequests[1].view_filters).saved.date, 'all');
  acknowledgments.shift()({ok: true});
  await vm.runInContext('settingWriteQueue', context);
  console.log('Workflow regressions passed: independent filters, defaults, restore, pending edits, failure/retry, serialized saves');
})().catch(error => { console.error(error); process.exitCode = 1; });
`);
